import asyncio
from unittest.mock import AsyncMock, MagicMock

import pytest

from services.document_ingestion_service import DocumentIngestionService
from services.llm_service import LLMService


class FakeEmbeddingService:
    async def embed_documents(self, texts: list[str], *args, **kwargs) -> list[list[float]]:
        return [[float(idx), 1.0] for idx, _ in enumerate(texts)]


class FakeResponse:
    def __init__(self, text: str):
        self.text = text


def test_summarize_document_parses_json_cleanly():
    service = LLMService.__new__(LLMService)
    service._generate_with_fallback = AsyncMock(
        return_value=FakeResponse(
            '{"summary": "This is a concise executive summary of the document.", "keywords": ["ai", "spaces", "search", "rag"]}'
        )
    )

    summary, keywords = asyncio.run(
        service.summarize_document(
            file_name="project_overview.txt",
            text="Spaces is an AI-powered personal workspace for indexing, searching, and managing files.",
        )
    )

    assert summary == "This is a concise executive summary of the document."
    assert keywords == ["ai", "spaces", "search", "rag"]


def test_summarize_document_handles_markdown_fences():
    service = LLMService.__new__(LLMService)
    service._generate_with_fallback = AsyncMock(
        return_value=FakeResponse(
            '```json\n{"summary": "Report on annual financial growth.", "keywords": ["finance", "revenue", "growth"]}\n```'
        )
    )

    summary, keywords = asyncio.run(
        service.summarize_document(
            file_name="finances.md",
            text="Annual growth report showing 25% revenue increase in FY26.",
        )
    )

    assert summary == "Report on annual financial growth."
    assert keywords == ["finance", "revenue", "growth"]


def test_summarize_document_heuristic_fallback_on_error():
    service = LLMService.__new__(LLMService)
    service._generate_with_fallback = AsyncMock(side_effect=RuntimeError("Gemini quota exceeded"))

    summary, keywords = asyncio.run(
        service.summarize_document(
            file_name="meeting_notes.txt",
            text="First paragraph discusses project timeline and deliverable deadlines.\n\nSecond paragraph discusses budget allocations.",
        )
    )

    # Should not crash; returns heuristic summary and keywords
    assert "First paragraph discusses project timeline" in summary
    assert len(keywords) > 0


def test_ingestion_integrates_summary_and_keywords():
    fake_llm = MagicMock()
    fake_llm.summarize_document = AsyncMock(
        return_value=(
            "Executive summary generated by LLM.",
            ["summary", "ingestion", "test"],
        )
    )

    service = DocumentIngestionService(
        embedding_service=FakeEmbeddingService(),
        llm_service=fake_llm,
    )

    stages = []

    async def on_stage(stage: str):
        stages.append(stage)

    result = asyncio.run(
        service.ingest(
            file_id="test-file-id",
            space_id="test-space-id",
            owner_id="test-owner-id",
            file_name="overview.md",
            file_type="md",
            content=b"Introductory guide to Spaces AI system.\n\nDetails on chunking and indexing.",
            on_stage=on_stage,
        )
    )

    assert result.status == "READY"
    assert result.summary == "Executive summary generated by LLM."
    assert result.keywords == ["summary", "ingestion", "test"]
    assert "SUMMARIZING" in stages
    assert stages == ["EXTRACTING", "CHUNKING", "EMBEDDING", "SUMMARIZING"]
